// The last things copied, for the card's clipboard tab. Text only, kept in memory and gone when the app quits,
// except the ones the user pins: those are saved, stay on top and outlive Clear all.
// Anything a password manager marks as secret or passing is never kept.

import AppKit

final class Clipboard: ObservableObject {
    static let limit = 10
    static let pinnedKey = "pinnedCopies"
    // The markers apps agreed on at nspasteboard.org for contents that must not be recorded.
    private static let secret: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"), .init("org.nspasteboard.AutoGeneratedType"),
    ]

    @Published private(set) var items: [String] = []   // the unpinned history, newest first
    @Published private(set) var pinned = UserDefaults.standard.stringArray(forKey: pinnedKey) ?? []

    // What the tab lists: the pinned ones first.
    var all: [String] { pinned + items }
    private let board = NSPasteboard.general
    private var count = NSPasteboard.general.changeCount
    private var timer: Timer?

    // ponytail: the pasteboard sends no change notice, so its counter is polled twice a second.
    func start() {
        timer = .scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.check() }
    }

    // Turned off in Settings, it forgets what it had and takes nothing in.
    private func check() {
        guard board.changeCount != count else { return }
        count = board.changeCount
        guard UserDefaults.standard.bool(forKey: CardPart.clipboard.rawValue) else {
            if !items.isEmpty { items = [] }
            return
        }
        guard let types = board.types, Self.secret.isDisjoint(with: types), let text = board.string(forType: .string),
              !pinned.contains(text) else { return }
        items = Self.adding(text, to: items)
    }

    // Forgets the history but not the pins; whatever is on the pasteboard itself stays there.
    func clear() { items = [] }

    // Takes one copy out, pinned or not.
    func remove(_ text: String) {
        items.removeAll { $0 == text }
        guard pinned.contains(text) else { return }
        pinned.removeAll { $0 == text }
        UserDefaults.standard.set(pinned, forKey: Self.pinnedKey)
    }

    func togglePin(_ text: String) {
        (pinned, items) = Self.togglingPin(text, pinned: pinned, items: items)
        UserDefaults.standard.set(pinned, forKey: Self.pinnedKey)
    }

    // Pinning moves a copy to the end of the pins; unpinning puts it back at the top of the history.
    static func togglingPin(_ text: String, pinned: [String], items: [String]) -> (pinned: [String], items: [String]) {
        pinned.contains(text)
            ? (pinned.filter { $0 != text }, adding(text, to: items))
            : (pinned + [text], items.filter { $0 != text })
    }

    // Copying one again puts it on the pasteboard; the next check moves it to the top.
    func copy(_ text: String) {
        board.clearContents()
        board.setString(text, forType: .string)
    }

    enum Kind: Equatable {
        case link, color(NSColor), text
    }

    // What a copy is, for the mark beside it: a web link, a "#RRGGBB" colour, or text.
    static func kind(of text: String) -> Kind {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        if let color = NSColor(hex: trimmed) { return .color(color) }
        if !trimmed.contains(where: \.isWhitespace), let url = URL(string: trimmed), let scheme = url.scheme,
           ["http", "https"].contains(scheme.lowercased()), url.host != nil { return .link }
        return .text
    }

    // Newest first, each text once, blank text ignored, the oldest dropped past the limit.
    static func adding(_ text: String, to items: [String]) -> [String] {
        guard !text.allSatisfy(\.isWhitespace) else { return items }
        return Array(([text] + items.filter { $0 != text }).prefix(limit))
    }
}
